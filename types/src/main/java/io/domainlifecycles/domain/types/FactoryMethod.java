package io.domainlifecycles.domain.types;

import java.lang.annotation.ElementType;
import java.lang.annotation.Retention;
import java.lang.annotation.RetentionPolicy;
import java.lang.annotation.Target;

/**
 * Marks a method creating a domain object - a factory method in the sense of Domain-Driven Design, with a name of the
 * ubiquitous language: a static method of an aggregate root, entity or value object creating an instance of it, a
 * method of an aggregate creating another aggregate, or a method of a service kind creating a domain object among its
 * other operations. The created type is the method's return type.
 * <p>
 * The public methods of a {@link Factory} returning a domain object are factory methods without this annotation.
 * Builders, e.g. the ones Lombok generates, are a technical means of construction and no factory methods.
 *
 * @author Mario Herb
 */
@Retention(RetentionPolicy.RUNTIME)
@Target({ElementType.METHOD})
public @interface FactoryMethod {

}
