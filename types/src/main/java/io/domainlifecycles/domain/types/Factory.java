package io.domainlifecycles.domain.types;

/**
 * This is the common supertype (marker interface) to represent Factories: classes whose only responsibility is to
 * create domain objects - e.g. because the creation is complex, or needs other services.
 * <p>
 * Every public method of a Factory returning a domain object is a factory method creating it; it needs no
 * {@link FactoryMethod} annotation. A service kind creating domain objects among other operations marks the creating
 * methods with {@link FactoryMethod} instead.
 *
 * @author Mario Herb
 */
public interface Factory extends ServiceKind {
}
